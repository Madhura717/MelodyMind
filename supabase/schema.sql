-- MelodyMind (Vite) - minimal Supabase schema for dashboard time tracking
-- Run this in Supabase -> SQL Editor

-- 1) Table
create table if not exists public.screen_time (
  id bigint generated by default as identity primary key,
  day text not null,
  minutes int not null default 0,
  "limit" int not null default 45,
  sort int not null default 0,
  created_at timestamptz not null default now()
);

-- Stable ordering + one row per day label
create unique index if not exists screen_time_day_unique on public.screen_time(day);
create index if not exists screen_time_sort_idx on public.screen_time(sort);

-- 2) RLS + policies
alter table public.screen_time enable row level security;

-- Allow the app (anon key) to READ rows (required for your current frontend)
drop policy if exists screen_time_read_anon on public.screen_time;
create policy screen_time_read_anon
on public.screen_time
for select
to anon
using (true);

