-- 1) Ensure table exists (minimal shape)
create table if not exists public.screen_time (
  id bigint generated by default as identity primary key,
  day text not null,
  minutes int not null default 0,
  "limit" int not null default 45,
  sort int not null default 0,
  created_at timestamptz not null default now()
);

-- 2) If table existed with missing columns, add them
alter table public.screen_time
  add column if not exists minutes int not null default 0;

alter table public.screen_time
  add column if not exists "limit" int not null default 45;

alter table public.screen_time
  add column if not exists sort int not null default 0;

alter table public.screen_time
  add column if not exists created_at timestamptz not null default now();

-- 3) Indexes for stable ordering/upsert
create unique index if not exists screen_time_day_unique on public.screen_time(day);
create index if not exists screen_time_sort_idx on public.screen_time(sort);

-- 4) RLS must be enabled, and anon must be allowed to SELECT
alter table public.screen_time enable row level security;

drop policy if exists screen_time_read_anon on public.screen_time;
create policy screen_time_read_anon
on public.screen_time
for select
to anon
using (true);

